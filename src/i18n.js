const languageKey = 'portfolio-3-language';

export function getLanguage() {
  try {
    return localStorage.getItem(languageKey) === 'th' ? 'th' : 'en';
  } catch {
    return 'en';
  }
}

export function saveLanguage(language) {
  try {
    localStorage.setItem(languageKey, language);
  } catch {
    // The language still applies for this page.
  }
}

export function translate(language, text) {
  return language === 'th' && Object.hasOwn(thai, text) ? thai[text] : text;
}
